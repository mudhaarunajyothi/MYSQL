View:
-----------
View is a virtual table or logical table
View not store the data it store select sql query
the views are created using select query

Advantages of views:
-----------------------
1) security
2) to avoid unneccesary columns in table
3) simplify complex queries
4) maintain readability

Types of views:
-------------------
1)simple view
2)complex view

1)Simple view:
---------------
the simple view is created from one table,does contain any complex
operations like joins,agregrate functions,cluses(group by,having)

2)Complex view:
----------------
the view is created from one or more than one table,does contain
joins,aggregate functions and cluses

Syntax:
----------
create view view_name select query;

